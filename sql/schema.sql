-- PayOps Phase 0.5 schema (PostgreSQL 14+). Run order is dependency order.
-- Windows run:  psql -U postgres -d payops -f sql\schema.sql   (create DB first: createdb -U postgres payops)
-- Re-run safely: this script DROPs and recreates everything (DEV ONLY).

DROP VIEW IF EXISTS v_unbalanced_journal;
DROP TABLE IF EXISTS reconciliation_result CASCADE;
DROP TABLE IF EXISTS reconciliation_run CASCADE;
DROP TABLE IF EXISTS posting CASCADE;
DROP TABLE IF EXISTS journal_entry CASCADE;
DROP TABLE IF EXISTS settlement_record CASCADE;
DROP TABLE IF EXISTS settlement_file CASCADE;
DROP TABLE IF EXISTS payment_event CASCADE;
DROP TABLE IF EXISTS payment CASCADE;
DROP TABLE IF EXISTS account CASCADE;
DROP TABLE IF EXISTS merchant CASCADE;
DROP TABLE IF EXISTS switch_database CASCADE;
DROP TABLE IF EXISTS app_user CASCADE;
DROP TABLE IF EXISTS role CASCADE;
DROP TABLE IF EXISTS user_role CASCADE;

-- Role: A job title that decides what a person may do (ADMIN, OPS_ENGINEER, FINANCE, SUPPORT).
CREATE TABLE role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(30) NOT NULL,
    description VARCHAR(200),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    CONSTRAINT pk_role PRIMARY KEY (id),
    CONSTRAINT ck_role_name CHECK (name IN ('ADMIN', 'OPS_ENGINEER', 'FINANCE', 'SUPPORT'))
);


-- User: A person who logs in to PayOps. Table is app_user because "user" is reserved in PostgreSQL.
CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(100),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    last_login_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    merchant_id BIGINT,
    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT uq_app_user_username UNIQUE (username),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_status CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED')),
    CONSTRAINT fk_app_user_merchant_id FOREIGN KEY (merchant_id) REFERENCES merchant(id) ON DELETE SET NULL
);
CREATE INDEX idx_app_user_status ON app_user (status);
CREATE INDEX idx_app_user_merchant_id ON app_user (merchant_id);

-- Join table User <-> Role (many-to-many)
CREATE TABLE user_role (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user_id FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_role_role_id FOREIGN KEY (role_id) REFERENCES role(id) ON DELETE CASCADE
);
CREATE INDEX idx_user_role_role_id ON user_role (role_id);

-- SwitchDatabase: ASSUMPTION: routing/connection profile of one bank, acquirer or network the transaction switch can send payments to.
CREATE TABLE switch_database (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    switch_type VARCHAR(30) NOT NULL,
    protocol VARCHAR(30) NOT NULL,
    host VARCHAR(255),
    port INTEGER,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    priority INTEGER NOT NULL DEFAULT 1,
    timeout_ms INTEGER NOT NULL DEFAULT 30000,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_switch_database PRIMARY KEY (id),
    CONSTRAINT uq_switch_database_code UNIQUE (code),
    CONSTRAINT ck_switch_database_switch_type CHECK (switch_type IN ('BANK', 'ACQUIRER', 'NETWORK')),
    CONSTRAINT ck_switch_database_protocol CHECK (protocol IN ('ISO8583', 'REST', 'SFTP')),
    CONSTRAINT ck_switch_database_port CHECK (port BETWEEN 1 AND 65535),
    CONSTRAINT ck_switch_database_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'MAINTENANCE')),
    CONSTRAINT ck_switch_database_priority CHECK (priority > 0),
    CONSTRAINT ck_switch_database_timeout_ms CHECK (timeout_ms > 0)
);


-- Merchant: A business that accepts payments through PayOps.
CREATE TABLE merchant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100),
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    default_switch_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_merchant PRIMARY KEY (id),
    CONSTRAINT uq_merchant_code UNIQUE (code),
    CONSTRAINT ck_merchant_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    CONSTRAINT fk_merchant_default_switch_id FOREIGN KEY (default_switch_id) REFERENCES switch_database(id) ON DELETE SET NULL
);
CREATE INDEX idx_merchant_default_switch_id ON merchant (default_switch_id);
CREATE INDEX idx_merchant_status ON merchant (status);

-- Account: A ledger account (chart of accounts) that postings debit or credit.
CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    account_type VARCHAR(30) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    merchant_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_account PRIMARY KEY (id),
    CONSTRAINT uq_account_code UNIQUE (code),
    CONSTRAINT ck_account_account_type CHECK (account_type IN ('ASSET', 'LIABILITY', 'REVENUE', 'EXPENSE', 'EQUITY')),
    CONSTRAINT fk_account_merchant_id FOREIGN KEY (merchant_id) REFERENCES merchant(id) ON DELETE RESTRICT
);
CREATE INDEX idx_account_merchant_id ON account (merchant_id);

-- Payment: One customer payment made to a merchant and routed through a switch. Central table.
CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(50) NOT NULL,
    merchant_id BIGINT NOT NULL,
    switch_database_id BIGINT NOT NULL,
    amount NUMERIC(19,4) NOT NULL,
    refunded_amount NUMERIC(19,4) NOT NULL DEFAULT 0,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    method VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'INITIATED',
    switch_reference VARCHAR(50),
    customer_ref VARCHAR(100),
    failure_reason VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_payment PRIMARY KEY (id),
    CONSTRAINT uq_payment_reference UNIQUE (reference),
    CONSTRAINT fk_payment_merchant_id FOREIGN KEY (merchant_id) REFERENCES merchant(id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_switch_database_id FOREIGN KEY (switch_database_id) REFERENCES switch_database(id) ON DELETE RESTRICT,
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_refunded_amount CHECK (refunded_amount >= 0 AND refunded_amount <= amount),
    CONSTRAINT ck_payment_method CHECK (method IN ('CARD', 'UPI', 'NETBANKING', 'WALLET')),
    CONSTRAINT ck_payment_status CHECK (status IN ('INITIATED', 'AUTHORIZED', 'CAPTURED', 'FAILED', 'REFUNDED', 'SETTLED'))
);
CREATE INDEX idx_payment_merchant_id ON payment (merchant_id);
CREATE INDEX idx_payment_switch_database_id ON payment (switch_database_id);
CREATE INDEX idx_payment_status ON payment (status);
CREATE INDEX idx_payment_created_at ON payment (created_at);
CREATE INDEX idx_payment_status_created_at ON payment (status, created_at);
CREATE INDEX idx_payment_switch_reference ON payment (switch_reference);

-- PaymentEvent: Append-only audit row written on every Payment state change.
CREATE TABLE payment_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_id BIGINT NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    amount NUMERIC(19,4),
    message VARCHAR(255),
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    CONSTRAINT pk_payment_event PRIMARY KEY (id),
    CONSTRAINT fk_payment_event_payment_id FOREIGN KEY (payment_id) REFERENCES payment(id) ON DELETE RESTRICT,
    CONSTRAINT ck_payment_event_event_type CHECK (event_type IN ('INITIATED', 'AUTHORIZED', 'CAPTURED', 'FAILED', 'REFUNDED', 'SETTLED'))
);
CREATE INDEX idx_payment_event_payment_id ON payment_event (payment_id);
CREATE INDEX idx_payment_event_payment_id_occurred_at ON payment_event (payment_id, occurred_at);

-- SettlementFile: One file received from a bank/acquirer listing settled transactions.
CREATE TABLE settlement_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    file_name VARCHAR(255) NOT NULL,
    switch_database_id BIGINT NOT NULL,
    settlement_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'RECEIVED',
    record_count INTEGER NOT NULL DEFAULT 0,
    total_amount NUMERIC(19,4) NOT NULL DEFAULT 0,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_settlement_file PRIMARY KEY (id),
    CONSTRAINT uq_settlement_file_file_name UNIQUE (file_name),
    CONSTRAINT fk_settlement_file_switch_database_id FOREIGN KEY (switch_database_id) REFERENCES switch_database(id) ON DELETE RESTRICT,
    CONSTRAINT ck_settlement_file_status CHECK (status IN ('RECEIVED', 'PARSED', 'FAILED', 'RECONCILED')),
    CONSTRAINT ck_settlement_file_record_count CHECK (record_count >= 0),
    CONSTRAINT ck_settlement_file_total_amount CHECK (total_amount >= 0)
);
CREATE INDEX idx_settlement_file_switch_database_id ON settlement_file (switch_database_id);
CREATE INDEX idx_settlement_file_status ON settlement_file (status);
CREATE INDEX idx_settlement_file_settlement_date ON settlement_file (settlement_date);

-- SettlementRecord: One transaction line inside a SettlementFile.
CREATE TABLE settlement_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    settlement_file_id BIGINT NOT NULL,
    payment_reference VARCHAR(50),
    bank_reference VARCHAR(100),
    payment_id BIGINT,
    amount NUMERIC(19,4) NOT NULL,
    fee NUMERIC(19,4) NOT NULL DEFAULT 0,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    transaction_date TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    CONSTRAINT pk_settlement_record PRIMARY KEY (id),
    CONSTRAINT fk_settlement_record_settlement_file_id FOREIGN KEY (settlement_file_id) REFERENCES settlement_file(id) ON DELETE CASCADE,
    CONSTRAINT fk_settlement_record_payment_id FOREIGN KEY (payment_id) REFERENCES payment(id) ON DELETE SET NULL,
    CONSTRAINT ck_settlement_record_amount CHECK (amount > 0),
    CONSTRAINT ck_settlement_record_fee CHECK (fee >= 0 AND fee <= amount)
);
CREATE INDEX idx_settlement_record_settlement_file_id ON settlement_record (settlement_file_id);
CREATE INDEX idx_settlement_record_payment_id ON settlement_record (payment_id);
CREATE INDEX idx_settlement_record_payment_reference ON settlement_record (payment_reference);
CREATE INDEX idx_settlement_record_bank_reference ON settlement_record (bank_reference);

-- JournalEntry: One accounting event (capture, refund, settlement). Holds balanced Postings.
CREATE TABLE journal_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entry_number VARCHAR(40) NOT NULL,
    source VARCHAR(30) NOT NULL,
    description VARCHAR(255),
    entry_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_id BIGINT,
    settlement_record_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    CONSTRAINT pk_journal_entry PRIMARY KEY (id),
    CONSTRAINT uq_journal_entry_entry_number UNIQUE (entry_number),
    CONSTRAINT ck_journal_entry_source CHECK (source IN ('PAYMENT_CAPTURE', 'REFUND', 'SETTLEMENT', 'MANUAL')),
    CONSTRAINT fk_journal_entry_payment_id FOREIGN KEY (payment_id) REFERENCES payment(id) ON DELETE RESTRICT,
    CONSTRAINT fk_journal_entry_settlement_record_id FOREIGN KEY (settlement_record_id) REFERENCES settlement_record(id) ON DELETE RESTRICT
);
CREATE INDEX idx_journal_entry_payment_id ON journal_entry (payment_id);
CREATE INDEX idx_journal_entry_settlement_record_id ON journal_entry (settlement_record_id);
CREATE INDEX idx_journal_entry_entry_date ON journal_entry (entry_date);

-- Posting: One debit or credit line of a JournalEntry against an Account.
CREATE TABLE posting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    journal_entry_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    direction VARCHAR(30) NOT NULL,
    amount NUMERIC(19,4) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    CONSTRAINT pk_posting PRIMARY KEY (id),
    CONSTRAINT fk_posting_journal_entry_id FOREIGN KEY (journal_entry_id) REFERENCES journal_entry(id) ON DELETE RESTRICT,
    CONSTRAINT fk_posting_account_id FOREIGN KEY (account_id) REFERENCES account(id) ON DELETE RESTRICT,
    CONSTRAINT ck_posting_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_posting_amount CHECK (amount > 0)
);
CREATE INDEX idx_posting_journal_entry_id ON posting (journal_entry_id);
CREATE INDEX idx_posting_account_id ON posting (account_id);

-- ReconciliationRun: One execution of the comparison between a SettlementFile and Payments.
CREATE TABLE reconciliation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_number VARCHAR(40) NOT NULL,
    settlement_file_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'RUNNING',
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    total_checked INTEGER NOT NULL DEFAULT 0,
    matched_count INTEGER NOT NULL DEFAULT 0,
    exception_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    CONSTRAINT pk_reconciliation_run PRIMARY KEY (id),
    CONSTRAINT uq_reconciliation_run_run_number UNIQUE (run_number),
    CONSTRAINT fk_reconciliation_run_settlement_file_id FOREIGN KEY (settlement_file_id) REFERENCES settlement_file(id) ON DELETE RESTRICT,
    CONSTRAINT ck_reconciliation_run_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_reconciliation_run_total_checked CHECK (total_checked >= 0),
    CONSTRAINT ck_reconciliation_run_matched_count CHECK (matched_count >= 0),
    CONSTRAINT ck_reconciliation_run_exception_count CHECK (exception_count >= 0)
);
CREATE INDEX idx_reconciliation_run_settlement_file_id ON reconciliation_run (settlement_file_id);
CREATE INDEX idx_reconciliation_run_status ON reconciliation_run (status);

-- ReconciliationResult: One outcome row of a run for one settlement record / payment.
CREATE TABLE reconciliation_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reconciliation_run_id BIGINT NOT NULL,
    settlement_record_id BIGINT,
    payment_id BIGINT,
    result_type VARCHAR(30) NOT NULL,
    expected_amount NUMERIC(19,4),
    actual_amount NUMERIC(19,4),
    note VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(50),
    CONSTRAINT pk_reconciliation_result PRIMARY KEY (id),
    CONSTRAINT fk_reconciliation_result_reconciliation_run_id FOREIGN KEY (reconciliation_run_id) REFERENCES reconciliation_run(id) ON DELETE CASCADE,
    CONSTRAINT fk_reconciliation_result_settlement_record_id FOREIGN KEY (settlement_record_id) REFERENCES settlement_record(id) ON DELETE SET NULL,
    CONSTRAINT fk_reconciliation_result_payment_id FOREIGN KEY (payment_id) REFERENCES payment(id) ON DELETE SET NULL,
    CONSTRAINT ck_reconciliation_result_result_type CHECK (result_type IN ('MATCHED', 'AMOUNT_MISMATCH', 'MISSING_IN_SETTLEMENT', 'MISSING_IN_PAYMENTS', 'DUPLICATE')),
    CONSTRAINT ck_reconciliation_result_side CHECK (settlement_record_id IS NOT NULL OR payment_id IS NOT NULL)
);
CREATE INDEX idx_reconciliation_result_reconciliation_run_id ON reconciliation_result (reconciliation_run_id);
CREATE INDEX idx_reconciliation_result_settlement_record_id ON reconciliation_result (settlement_record_id);
CREATE INDEX idx_reconciliation_result_payment_id ON reconciliation_result (payment_id);
CREATE INDEX idx_reconciliation_result_result_type ON reconciliation_result (result_type);

-- Audit helper: lists journal entries whose debits <> credits (should always be empty)
CREATE VIEW v_unbalanced_journal AS
SELECT journal_entry_id,
       SUM(CASE WHEN direction = 'DEBIT'  THEN amount ELSE 0 END) AS total_debit,
       SUM(CASE WHEN direction = 'CREDIT' THEN amount ELSE 0 END) AS total_credit
FROM posting GROUP BY journal_entry_id
HAVING SUM(CASE WHEN direction = 'DEBIT' THEN amount ELSE 0 END)
    <> SUM(CASE WHEN direction = 'CREDIT' THEN amount ELSE 0 END);

